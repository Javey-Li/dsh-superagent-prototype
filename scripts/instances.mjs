#!/usr/bin/env node
/** Manage one DSH profile per project from deploy/projects.json. */

import { spawnSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const MANIFEST = join(ROOT, 'deploy', 'projects.json')
const SERVICE = join(ROOT, 'scripts', 'dsh-superagent')
const DSH_HOME = process.env.DSH_HOME || join(homedir(), '.dsh')

const expandHome = value => value.replace(/^~(?=$|\/)/, homedir())

function loadManifest() {
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'))
  if (manifest.version !== 1) throw new Error(`deploy/projects.json: unsupported version ${manifest.version}`)
  const defaults = manifest.defaults ?? {}
  const projects = Object.entries(manifest.projects ?? {})
  if (!projects.length) throw new Error('deploy/projects.json: no projects')

  const seen = { profile: new Map(), port: new Map(), stateDir: new Map() }
  const entries = projects.map(([name, project]) => {
    const entry = {
      name,
      host: project.host ?? defaults.host ?? '127.0.0.1',
      profile: project.profile,
      port: project.port,
      stateDir: project.stateDir,
      model: { ...defaults.model, ...project.model },
      env: { ...defaults.env, ...project.env },
      repository: project.repository,
      maxWorkers: project.maxWorkers,
      settings: project.settings ?? {},
    }
    if (!entry.profile || !/^[a-z][a-z0-9-]*$/.test(entry.profile)) throw new Error(`${name}: profile must match [a-z][a-z0-9-]*`)
    if (!Number.isInteger(entry.port) || entry.port < 1024 || entry.port > 65535) throw new Error(`${name}: port must be an integer from 1024 to 65535`)
    if (!entry.stateDir) throw new Error(`${name}: stateDir is required`)
    entry.stateDir = expandHome(entry.stateDir)
    if (!entry.stateDir.startsWith('/')) throw new Error(`${name}: stateDir must be absolute after ~ expansion`)
    for (const key of ['profile', 'port', 'stateDir']) {
      const other = seen[key].get(entry[key])
      if (other) throw new Error(`${name}: ${key} ${entry[key]} is already used by ${other}`)
      seen[key].set(entry[key], name)
    }
    return entry
  })
  return { entries, project: name => entries.find(entry => entry.name === name) }
}

function scalar(value) {
  if (value === null) return 'null'
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  const text = String(value)
  const plain = /^[A-Za-z0-9_./:@+-]+$/.test(text) && !/^(true|false|null|yes|no|on|off)$/i.test(text)
  return plain ? text : JSON.stringify(text)
}

function yamlLines(value, indent = 0) {
  const pad = ' '.repeat(indent)
  if (Array.isArray(value)) {
    if (!value.length) return [`${pad}[]`]
    return value.flatMap(item => {
      if (item && typeof item === 'object' && !Array.isArray(item)) {
        const lines = yamlLines(item, indent + 2)
        return [`${pad}- ${lines.shift().trimStart()}`, ...lines]
      }
      return [`${pad}- ${scalar(item)}`]
    })
  }
  if (value && typeof value === 'object') {
    const entries = Object.entries(value)
    if (!entries.length) return [`${pad}{}`]
    return entries.flatMap(([key, item]) => item && typeof item === 'object'
      ? [`${pad}${scalar(key)}:`, ...yamlLines(item, indent + 2)]
      : [`${pad}${scalar(key)}: ${scalar(item)}`])
  }
  return [`${pad}${scalar(value)}`]
}

function profilePatch(entry) {
  const { model } = entry
  if (!model.provider || !model.model) throw new Error(`${entry.name}: defaults.model.provider and defaults.model.model are required`)
  const modelProfile = {
    id: model.model,
    ...(model.name ? { name: model.name } : {}),
    ...(model.contextWindow ? { contextWindow: model.contextWindow } : {}),
    ...(model.maxTokens ? { maxTokens: model.maxTokens } : {}),
  }
  const patch = [
    { id: 'webserver', config: { host: entry.host, port: entry.port } },
    { id: 'agent-default-model', config: { provider: model.provider, model: model.model } },
    {
      id: 'llm-pi-ai',
      config: {
        providers: {
          [model.provider]: {
            displayName: model.displayName ?? model.provider,
            ...(model.apiKeyEnv ? { apiKeyEnv: model.apiKeyEnv } : {}),
            api: model.api ?? 'openai-completions',
            baseURL: model.baseURL,
            models: [modelProfile],
          },
        },
      },
    },
    { id: 'dsh-superagent', config: { stateDir: entry.stateDir } },
  ]
  return [
    `# Generated by scripts/instances.mjs for ${entry.name}; edit deploy/projects.json instead.`,
    ...yamlLines(patch),
    '',
  ].join('\n')
}

function profileDir(entry) {
  return join(DSH_HOME, 'profiles', entry.profile)
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, { cwd: ROOT, stdio: 'inherit', ...options })
  if (result.error) throw result.error
  return result.status ?? 1
}

function writeProfile(entry) {
  const directory = profileDir(entry)
  const target = join(directory, 'cordis.patch.yml')
  mkdirSync(directory, { recursive: true })
  const content = profilePatch(entry)
  if (existsSync(target)) {
    const previous = readFileSync(target, 'utf8')
    if (previous === content) return target
    const stamp = new Date().toISOString().replace(/[-:]/g, '').replace(/\..+/, '')
    copyFileSync(target, `${target}.bak-${stamp}`)
  }
  writeFileSync(target, content)
  return target
}

function provision(entry) {
  const directory = profileDir(entry)
  if (!existsSync(directory)) {
    const status = run('dsh', [entry.profile, '--from-default-profile', 'web', '--dump-config'], { stdio: 'ignore' })
    if (status !== 0) throw new Error(`dsh could not create profile ${entry.profile}`)
  }
  const packagePath = join(directory, 'package.json')
  const packageJson = existsSync(packagePath) ? JSON.parse(readFileSync(packagePath, 'utf8')) : {}
  const linked = Object.values(packageJson.dependencies ?? {}).includes(`link:${ROOT}`)
  if (!linked) {
    const status = run('dsh', ['plugin', '--profile', entry.profile, 'add', `link:${ROOT}`])
    if (status !== 0) throw new Error(`dsh could not install the bundle into ${entry.profile}`)
  }
  const patch = writeProfile(entry)
  console.log(`Profile: ${entry.profile}`)
  console.log(`Patch:   ${patch}`)
  console.log(`URL:     ${urlOf(entry)}`)
  console.log(`Next:    node scripts/instances.mjs start ${entry.name}`)
}

function urlOf(entry) {
  return `http://${entry.host}:${entry.port}`
}

function seedTmux(entry) {
  const values = { ...entry.env }
  if (process.env.T3_MCP_TOKEN) values.T3_MCP_TOKEN = process.env.T3_MCP_TOKEN
  for (const [key, value] of Object.entries(values)) {
    if (value === undefined) continue
    const result = spawnSync('tmux', ['set-environment', '-g', key, String(value)], { stdio: 'ignore' })
    if (result.error) return
  }
}

function service(entry, action, options = {}) {
  seedTmux(entry)
  return run('python3', [SERVICE, action, '--profile', entry.profile, '--url', urlOf(entry)],
    { env: { ...process.env, ...entry.env }, ...options })
}

async function api(entry, path, method = 'GET', body) {
  const response = await fetch(`${urlOf(entry)}/orchestrator/api/${path}`, {
    method,
    headers: {
      'x-orchestrator-request': '1',
      ...(body === undefined ? {} : { 'content-type': 'application/json' }),
    },
    body: body === undefined ? undefined : JSON.stringify(body),
  })
  const text = await response.text()
  let value
  try { value = JSON.parse(text) } catch { value = text }
  if (!response.ok) throw new Error(`${method} ${path}: ${response.status} ${typeof value === 'string' ? value : JSON.stringify(value)}`)
  return value
}

function merge(base, override) {
  if (!override || typeof override !== 'object' || Array.isArray(override)) return override
  const result = { ...(base && typeof base === 'object' && !Array.isArray(base) ? base : {}) }
  for (const [key, value] of Object.entries(override)) result[key] = merge(result[key], value)
  return result
}

function expandPaths(value) {
  if (typeof value === 'string') return expandHome(value)
  if (Array.isArray(value)) return value.map(expandPaths)
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, expandPaths(item)]))
  return value
}

async function waitReady(entry) {
  const deadline = Date.now() + 60_000
  while (Date.now() < deadline) {
    try {
      const current = await api(entry, 'state')
      if (current.health?.runtime?.state === 'ready' || current.health?.runtime?.state === 'paused') return current
    } catch { /* The service restarts during a setup change. */ }
    await new Promise(resolve => setTimeout(resolve, 1000))
  }
  throw new Error(`${entry.name}: timed out waiting for ${urlOf(entry)}`)
}

async function configure(entry) {
  const settings = await api(entry, 'settings')
  for (const [block, raw] of Object.entries(entry.settings)) {
    const override = expandPaths(raw)
    let value
    let revision
    if (block.startsWith('source:')) {
      const source = settings.sources.find(item => `source:${item.id}` === block)
      if (!source) throw new Error(`${entry.name}: source ${block} is not installed`)
      value = merge(source.value, override)
      revision = source.revision
    } else {
      const current = settings.blocks[block]
      if (!current) throw new Error(`${entry.name}: settings block ${block} does not exist`)
      value = merge(current.value, override)
      revision = current.revision
    }
    const saved = await api(entry, `settings/${block}`, 'PUT', { value, revision })
    console.log(`${block}: revision ${saved.revision}${saved.restarting ? ' (restarting)' : ''}`)
    if (saved.restarting) await waitReady(entry)
  }
}

function status(entry) {
  const code = service(entry, 'status')
  if (code !== 0) console.log(`${entry.name}: status exit ${code}`)
  return code
}

function list(manifest) {
  for (const entry of manifest.entries) {
    console.log(`${entry.name}\t${entry.profile}\t${urlOf(entry)}\t${entry.stateDir}\t${entry.repository ?? ''}`)
  }
}

function statusAll(manifest) {
  let code = 0
  for (const entry of manifest.entries) {
    console.log(`=== ${entry.name} (${entry.profile}, ${urlOf(entry)}) ===`)
    code = Math.max(code, status(entry))
  }
  return code
}

function usage() {
  console.log(`Usage: node scripts/instances.mjs <command> [project]

Commands:
  list                 Print every project, profile, URL and state directory.
  render <project>     Print the generated profile patch without writing it.
  provision <project>  Create the DSH profile if needed, link this checkout, write the patch.
  configure <project>  Merge the project's settings into the running instance over the management API.
  url <project>        Print the instance URL.
  status [project]     Show runtime status; with no project, show every instance.
  start|stop|restart <project>
                       Run scripts/dsh-superagent for the project's profile and URL.

Set DSH_HOME to relocate ~/.dsh.`)
}

async function main() {
  const [command = 'list', name, ...rest] = process.argv.slice(2)
  const manifest = loadManifest()
  if (command === 'list') return void list(manifest)
  if (command === 'help' || command === '--help' || command === '-h') return void usage()
  if (command === 'status' && !name) {
    process.exitCode = statusAll(manifest)
    return
  }
  if (!name) throw new Error(`${command} needs a project name; run list to see them`)
  if (rest.length) throw new Error(`Unexpected arguments: ${rest.join(' ')}`)
  const entry = manifest.project(name)
  if (!entry) throw new Error(`Unknown project ${name}`)

  switch (command) {
    case 'render':
      process.stdout.write(profilePatch(entry))
      return
    case 'provision':
      return void provision(entry)
    case 'configure':
      return void await configure(entry)
    case 'url':
      return void console.log(urlOf(entry))
    case 'status':
      process.exitCode = status(entry)
      return
    case 'start':
    case 'stop':
    case 'restart':
      process.exitCode = service(entry, command)
      return
    default:
      usage()
      throw new Error(`Unknown command ${command}`)
  }
}

main().catch(error => {
  console.error(error instanceof Error ? error.message : String(error))
  process.exitCode = 1
})
